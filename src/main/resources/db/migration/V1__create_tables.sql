-- =====================================================================
-- ClyvoVet - Schema inicial
-- O Hibernate roda com ddl-auto=validate, entao este arquivo e a UNICA
-- fonte de verdade do schema. Qualquer divergencia com as entidades JPA
-- derruba a aplicacao no boot (que e exatamente o comportamento desejado).
-- =====================================================================

-- ---------------------------------------------------------------------
-- Autenticacao: usuario do painel web e do app mobile.
-- Separado de DONOS de proposito: nem todo usuario e tutor (ex.: ADMIN).
-- ---------------------------------------------------------------------
CREATE TABLE USUARIOS (
    usuario_id    BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_email VARCHAR(100)  NOT NULL,
    -- hash BCrypt ocupa 60 chars; 100 da folga para trocar de algoritmo
    usuario_senha VARCHAR(100)  NOT NULL,
    usuario_role  VARCHAR(20)   NOT NULL,
    CONSTRAINT UQ_USUARIO_EMAIL UNIQUE (usuario_email)
);

-- ---------------------------------------------------------------------
-- Tutores
-- ---------------------------------------------------------------------
CREATE TABLE DONOS (
    dono_id       BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dono_nome     VARCHAR(50)  NOT NULL,
    dono_email    VARCHAR(50)  NOT NULL,
    dono_telefone VARCHAR(20)  NOT NULL,
    CONSTRAINT UQ_DONO_EMAIL UNIQUE (dono_email)
);

-- ---------------------------------------------------------------------
-- Equipe da clinica
-- ---------------------------------------------------------------------
CREATE TABLE FUNCIONARIOS (
    funcionario_id       BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    funcionario_nome     VARCHAR(50)  NOT NULL,
    funcionario_setor    VARCHAR(50)  NOT NULL,
    funcionario_cargo    VARCHAR(50)  NOT NULL,
    funcionario_email    VARCHAR(50)  NOT NULL,
    funcionario_telefone VARCHAR(20)  NOT NULL,
    CONSTRAINT UQ_FUNC_EMAIL UNIQUE (funcionario_email)
);

-- ---------------------------------------------------------------------
-- Pets
-- Guardamos data de nascimento (nao "idade"): idade e informacao derivada
-- e ficaria desatualizada no banco. O DTO calcula e devolve "3 anos".
-- ---------------------------------------------------------------------
CREATE TABLE PETS (
    pet_id              BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pet_nome            VARCHAR(50)   NOT NULL,
    pet_data_nascimento DATE          NOT NULL,
    pet_peso            NUMERIC(5,2)  NOT NULL,
    pet_especie         VARCHAR(50)   NOT NULL,
    pet_raca            VARCHAR(50)   NOT NULL,
    dono_id             BIGINT        NOT NULL,
    CONSTRAINT PETS_DONOS_FK FOREIGN KEY (dono_id) REFERENCES DONOS (dono_id)
);

-- ---------------------------------------------------------------------
-- Calendario vacinal.  vacina_status: 'P' = pendente, 'A' = aplicada
-- ---------------------------------------------------------------------
CREATE TABLE VACINAS (
    vacina_id     BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vacina_nome   VARCHAR(50)  NOT NULL,
    vacina_data   DATE         NOT NULL,
    vacina_status VARCHAR(1)   NOT NULL,
    pet_id        BIGINT       NOT NULL,
    CONSTRAINT VACINAS_PETS_FK FOREIGN KEY (pet_id) REFERENCES PETS (pet_id)
);

-- ---------------------------------------------------------------------
-- Medicamentos
-- ---------------------------------------------------------------------
CREATE TABLE MEDICAMENTOS (
    medicamento_id   BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicamento_nome VARCHAR(100)  NOT NULL
);

-- ---------------------------------------------------------------------
-- Consultas.  consulta_status: 'A' = agendada, 'R' = realizada, 'C' = cancelada
-- ---------------------------------------------------------------------
CREATE TABLE CONSULTAS (
    consulta_id        BIGINT         GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consulta_tipo      VARCHAR(50)    NOT NULL,
    consulta_valor     NUMERIC(10,2)  NOT NULL,
    consulta_descricao VARCHAR(500)   NOT NULL,
    consulta_status    VARCHAR(1)     NOT NULL,
    consulta_data      TIMESTAMP      NOT NULL,
    pet_id             BIGINT         NOT NULL,
    funcionario_id     BIGINT         NOT NULL,
    CONSTRAINT CONSULTAS_PETS_FK FOREIGN KEY (pet_id) REFERENCES PETS (pet_id),
    CONSTRAINT CONSULTAS_FUNCIONARIOS_FK FOREIGN KEY (funcionario_id) REFERENCES FUNCIONARIOS (funcionario_id)
);

-- ---------------------------------------------------------------------
-- Associativa consulta <-> medicamento (com a dosagem prescrita)
-- ---------------------------------------------------------------------
CREATE TABLE CONSULTAS_MEDICAMENTOS (
    consulta_medicamento_id BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    consulta_id             BIGINT        NOT NULL,
    medicamento_id          BIGINT        NOT NULL,
    cm_dosagem              VARCHAR(100)  NOT NULL,
    CONSTRAINT CM_CONSULTAS_FK FOREIGN KEY (consulta_id) REFERENCES CONSULTAS (consulta_id),
    CONSTRAINT CM_MEDICAMENTOS_FK FOREIGN KEY (medicamento_id) REFERENCES MEDICAMENTOS (medicamento_id)
);

-- Indices para os filtros mais usados pelo app mobile
CREATE INDEX IDX_PETS_DONO      ON PETS (dono_id);
CREATE INDEX IDX_VACINAS_PET    ON VACINAS (pet_id);
CREATE INDEX IDX_VACINAS_STATUS ON VACINAS (vacina_status);
CREATE INDEX IDX_CONSULTAS_PET  ON CONSULTAS (pet_id);
